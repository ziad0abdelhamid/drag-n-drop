export function getTranslation(lang = "en", key: string): string {
  const parts = key.split(".");
  let value: any =
    translations[lang as keyof typeof translations] || translations.en;

  for (const part of parts) {
    value = value[part];
    if (!value) return key;
  }

  return value;
}
